// Sample data of the finance and science types, as FinanceTypes, ScienceSamples and the Showroom* samples of the .NET
// version (ShowroomPrices, ShowroomPlans, ShowroomShapes, ShowroomGallery, ShowroomChecks). Each body is written once:
// the preview runs it, and the code the configurator writes repeats it. Times are milliseconds since 1970 in UTC.
import type { SampleInfo } from './catalog';

const sample = (info: SampleInfo): SampleInfo => info;
const lines = (...items: string[]): string => items.join('\n');

// The random walk of the share prices of the showroom: eight steps per period from 100, the same for a seed.
const walk = (id: string, name: string, count: number, period: string, seed: number): SampleInfo =>
  sample({
    id,
    name,
    shape: 'candles',
    defaultCount: count,
    minimumCount: 1,
    body: lines(
      'const data = new CandleData(count);',
      `const random = new SeededRandom(${String(seed)});`,
      'let price = 100;',
      'for (let i = 0; i < count; i++) {',
      '  const open = price;',
      '  let high = price;',
      '  let low = price;',
      '  for (let step = 0; step < 8; step++) {',
      '    price *= 1 + (random.nextDouble() - 0.5) * 0.012;',
      '    high = Math.max(high, price);',
      '    low = Math.min(low, price);',
      '  }',
      '  const volume = round(5000 + random.nextDouble() * 20000 * (1 + (Math.abs(price - open) / open) * 50));',
      `  data.append(Date.UTC(2024, 0, 2) + ${period} * i, open, high, low, price, volume);`,
      '}',
      'return data;',
    ),
    returns: 'CandleData',
    uses: ['CandleData', 'SeededRandom', 'round'],
  });

// A field of hills and a valley over 0 to 6, with a gap above 4.8 when asked for.
const hills = (gap: boolean): string =>
  lines(
    'const values = new Float32Array(count * count);',
    'for (let row = 0; row < count; row++) {',
    '  const y = (row * 6) / count;',
    '  for (let column = 0; column < count; column++) {',
    '    const x = (column * 6) / count;',
    `    values[row * count + column] = ${gap ? 'x > 4.8 && y > 4.8 ? Number.NaN : ' : ''}Math.sin(x) * Math.cos(y * 1.3) + 0.6 * Math.exp(-((x - 2) * (x - 2) + (y - 4) * (y - 4)));`,
    '  }',
    '}',
    'const data = new HeatmapData(count, count);',
    'data.setValues(values);',
  );

// A wobbly round ring, the same on every run.
const blob = lines(
  'const blob = (cx = 0, cy = 0, radius = 0, wobble = 0, corners = 0, seed = 0) => {',
  '  const x = new Float64Array(corners);',
  '  const y = new Float64Array(corners);',
  '  for (let i = 0; i < corners; i++) {',
  '    const angle = (i * 2 * Math.PI) / corners;',
  '    const r = radius + wobble * (0.5 * Math.sin(angle * 3 + seed) + 0.3 * Math.sin(angle * 7 + seed * 2) + 0.2 * Math.sin(angle * 11 + seed));',
  '    x[i] = cx + r * Math.cos(angle);',
  '    y[i] = cy + r * Math.sin(angle);',
  '  }',
  '  return new PolygonRing(x, y);',
  '};',
);

// A ring of evenly spaced corners.
const circle = lines(
  'const circle = (cx = 0, cy = 0, radius = 0, corners = 0) => {',
  '  const x = new Float64Array(corners);',
  '  const y = new Float64Array(corners);',
  '  for (let i = 0; i < corners; i++) {',
  '    const angle = (i * 2 * Math.PI) / corners;',
  '    x[i] = cx + radius * Math.cos(angle);',
  '    y[i] = cy + radius * Math.sin(angle);',
  '  }',
  '  return new PolygonRing(x, y);',
  '};',
);

// A tone that wanders and its overtone, row by row.
const tone = (rows: number, total: number, pauses: boolean): string =>
  lines(
    `const data = new SpectrogramData(count, ${String(rows)});`,
    'const row = new Float32Array(count);',
    `for (let index = 0; index < ${String(total)}; index++) {`,
    '  const center = count / 2 + (count / 2.5) * Math.sin(index * 0.03);',
    '  for (let i = 0; i < count; i++) {',
    '    const distance = (i - center) / 6;',
    '    const overtone = (i - center / 2) / 10;',
    `    row[i] = ${pauses ? 'index % 100 >= 60 && index % 100 < 66 ? Number.NaN : ' : ''}Math.exp(-distance * distance) + 0.4 * Math.exp(-overtone * overtone) + 0.05 * Math.sin(i * 0.9);`,
    '  }',
    '  data.appendRow(row);',
    '}',
    'return data;',
  );

