// Sample data of the 3D types, as Samples3D, ShowroomSamples3D, ShowroomModels3D and ShowroomVolumes3D of the .NET
// version. Each body is written once: the preview runs it, and the code the configurator writes repeats it.
import type { SampleInfo } from './catalog';

const threeD = '@tachyon-charts/3d';
const lines = (...items: string[]): string => items.join('\n');
const gauss =
  'const gauss = () => Math.sqrt(-2 * Math.log(1 - random.nextDouble())) * Math.cos(2 * Math.PI * random.nextDouble());';

const spiral = (
  id: string,
  name: string,
  count: number,
  turn: number,
  radius: number,
  color: string,
  uses: string[],
): SampleInfo => ({
  id,
  name,
  shape: 'points3D',
  defaultCount: count,
  minimumCount: 2,
  body: lines(
    'const path = new Points3D(count);',
    ...(color.includes('colormap') ? ["const colormap = Colormap.builtIn('Inferno');"] : []),
    'for (let i = 0; i < count; i++) {',
    `  const turn = i * ${String(turn)};`,
    `  path.append(Math.cos(turn) * ${String(radius)}, Math.sin(turn) * ${String(radius)}, i / (count / 2) - 1, ${color});`,
    '}',
    'return path;',
  ),
  returns: 'Points3D',
  uses: [`${threeD}#Points3D`, ...uses],
});

const rasterHills = lines(
  'const values = new Float32Array(count * count);',
  'for (let row = 0; row < count; row++) {',
  '  for (let column = 0; column < count; column++) {',
  '    const x = (column + 0.5) / count;',
  '    const y = (row + 0.5) / count;',
  '    values[row * count + column] = 0.15 + 0.85 * Math.exp(-14 * ((x - 0.35) * (x - 0.35) + (y - 0.6) * (y - 0.6))) + 0.35 * Math.exp(-30 * ((x - 0.8) * (x - 0.8) + (y - 0.25) * (y - 0.25)));',
  '  }',
  '}',
  'const data = new HeatmapData(count, count);',
  'data.setValues(values);',
  'return data;',
);

