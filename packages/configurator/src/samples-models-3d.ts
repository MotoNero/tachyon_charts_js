// Models of triangles for the 3D type Model, as ShowroomModels3D and ShowroomVolumes3D of the .NET version: meshes
// made in code, a knot of tube of a million triangles and a pipe bend read from STL with the temperature of its wall.
import type { SampleInfo } from './catalog';

const threeD = '@tachyon-charts/3d';
const lines = (...items: string[]): string => items.join('\n');

// A surface over -1 to 1 as a model of triangles with a color per corner, from blue below to orange above.
const surfaceMesh = (id: string, name: string, height: string): SampleInfo => ({
  id,
  name,
  shape: 'model',
  defaultCount: 96,
  hasCount: false,
  body: lines(
    'const side = 96;',
    'const positions = [];',
    'const colors = [];',
    'const triangles = [];',
    'for (let row = 0; row < side; row++) {',
    '  for (let column = 0; column < side; column++) {',
    '    const x = (column * 2) / (side - 1) - 1;',
    '    const y = (row * 2) / (side - 1) - 1;',
    `    const z = ${height};`,
    '    const share = (z + 1) / 2;',
    '    positions.push(new Point3D(x, y, z));',
    '    colors.push({ r: Math.trunc(40 + 215 * share), g: Math.trunc(110 + 60 * share), b: Math.trunc(230 - 170 * share), a: 255 });',
    '    if (row > 0 && column > 0) {',
    '      const corner = row * side + column;',
    '      triangles.push(corner - side - 1, corner - side, corner, corner - side - 1, corner, corner - 1);',
    '    }',
    '  }',
    '}',
    'return new ModelFileData(positions, triangles, colors);',
  ),
  returns: 'ModelFileData',
  uses: [`${threeD}#Point3D`, `${threeD}#ModelFileData`],
});

// The middle line of the pipe bend: along x, a quarter circle upward, then along z; its tangent.
const pipeLine = lines(
  'const leg = 40;',
  'const bend = 60;',
  'const outer = 15;',
  'const flangeThickness = 5;',
  'const length = 2 * leg + (bend * Math.PI) / 2;',
  'const middle = (s = 0) => {',
  '  if (s <= leg) {',
  '    return new Point3D(s, 0, 0);',
  '  }',
  '  const angle = (s - leg) / bend;',
  '  return angle <= Math.PI / 2',
  '    ? new Point3D(leg + bend * Math.sin(angle), 0, bend - bend * Math.cos(angle))',
  '    : new Point3D(leg + bend, 0, bend + (s - leg - (bend * Math.PI) / 2));',
  '};',
  'const tangent = (s = 0) => {',
  '  const angle = Math.min(Math.max((s - leg) / bend, 0), Math.PI / 2);',
  '  return new Point3D(Math.cos(angle), 0, Math.sin(angle));',
  '};',
  'const up = new Point3D(0, 1, 0);',
);

