/** The sample curves: a DataSource of `count` points over the length of each. */
export const curveSamples: readonly SampleInfo[] = curves.map((curve) => {
  const from = curve.start === 0 ? '' : `${String(curve.start)} + `;
  const usesRound = curve.formula.includes('round(');
  return {
    id: curve.id,
    name: curve.name,
    shape: 'points',
    defaultCount: curve.count,
    body: [
      'const data = new DataSource(count);',
      'for (let i = 0; i < count; i++) {',
      `  const x = ${from}(i * ${String(curve.length)}) / (count - 1);`,
      `  data.append(x, ${curve.formula});`,
      '}',
      'return data;',
    ].join('\n'),
    returns: 'DataSource',
    uses: usesRound ? ['DataSource', 'round'] : ['DataSource'],
  };
});
